def stress_record(tid: str, st: dict) -> str:
    title = next(t[1] for t in TASKS if t[0] == tid)
    s = st[tid]
    lines = [NOTE, "", f"سجل اختبار الصمود · {tid} · {title}",
             "من أجراه: هاشم السبيهي، مدرّس المقرر، بحساب مجاني في مساعد ذكاء اصطناعي عام من النوع الذي يستخدمه المتدربون.",
             "الطريقة: يُلصق وصف المهمة كما يصل إلى المتدرب، ويُؤخذ أول مخرج دون تعديل، ثم يُقيَّم بسلم تقدير المهمة نفسه.", "",
             f"ما أُعطي للمساعد: {s['given']}", f"الوقت حتى مخرج قابل للتسليم: {s['minutes']} دقائق" if s.get("minutes") else "الوقت: لا ينطبق",
             "", "المخرج (ملخص من المدرّس):", s["output"], ""]
    if tid == "T1":
        lines.append(f"النتيجة: {50 - len(s['wrong_items'])} إجابة صحيحة من 50. الأسئلة التي أخطأ فيها: {s['wrong_items'][0]} و{s['wrong_items'][1]}.")
    elif s.get("score") is not None:
        lines.append(f"الدرجة بسلم تقدير المهمة: {s['score']} من 100.")
        if tid == "T5":
            w = s["wrong_rows"]
            lines.append(f"بنود السجل التي قُدّرت درجتها خطأ قياسًا على حقائق الموقع: {w[0]} و{w[1]} و{w[2]} من 12.")
    else:
        lines.append("الدرجة: لا تنطبق. المهمة تُؤدى أمام المقيِّم أو تحت المراقبة، وما يُعدّ مسبقًا لا يدخل في الدرجة.")
    lines += ["", f"ملاحظة المدرّس: {s['note']}"]
    return "\n".join(lines)


