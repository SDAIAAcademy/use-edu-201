def exposure(score: int | None, supervised: bool) -> int:
    if supervised or score is None:
        return 0
    if score >= 70:
        return 3
    if score >= 50:
        return 2
    return 1


def build_stress(rng: random.Random) -> dict:
    """The stress-test record of each task, from the stand-in replies."""
    st = STANDIN["stress"]
    # T1: fifty quiz items, the assistant misses two
    items = list(range(1, 51))
    wrong = sorted(rng.sample(items, 2))
    st["T1"]["wrong_items"] = wrong
    st["T1"]["score"] = round((50 - len(wrong)) / 50 * 100)
    # T5: twelve register rows, three scored wrongly against the site facts
    rows = list(range(1, 13))
    st["T5"]["wrong_rows"] = sorted(rng.sample(rows, 3))
    return st


